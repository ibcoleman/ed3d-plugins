def build_evidence(content):
    """Build a valid evidence object from a content map (via the parser)."""
    roots = list(parser.EXPECTED_ROOTS)
    resources = []
    for uri in roots:
        text = content[uri]
        resources.append({
            "uri": uri,
            "parent_uri": None,
            "retrieval_status": "retrieved",
            "content": text,
            "content_sha256": parser.hash_content(text),
            "discovered_references": parser.references_from_scan(
                parser.scan_content(text)),
        })
    closure, unresolved = parser.recompute_evidence(roots, resources)
    semantic_sources = [
        {"claim_id": sid, "capability": cap, "url": SEM_TO_URI[sid],
         "revision_or_version": "polytoken-local-2026-09-01",
         "retrieval_date": "2026-09-01",
         "supported_claim": "Captured source supports %s." % sid,
         "evidence_class": "observed"}
        for cap, sids in CAP_TO_SEM.items() for sid in sids
    ]
    manual = [{"id": mid, "status": "pass", "note": "verified by operator"}
              for mid in parser.MANUAL_REVIEW_IDS]
    return {
        "roots": roots,
        "resources": resources,
        "unresolved_references": unresolved,
        "semantic_sources": semantic_sources,
        "local_citations": [dict(r) for r in LOCAL_CITATIONS],
        "workflow_stages": [dict(r) for r in WORKFLOW_STAGES],
        "case_study_citations": [dict(r) for r in CASE_STUDY_CITATIONS],
        "manual_review": manual,
    }


def build_audit(evidence):
    """Build the canonical valid audit markdown from the evidence object."""
    roots = list(parser.EXPECTED_ROOTS)
    lines = [
        "# Portability Audit",
        "",
        "## Executive answer",
        "Polytoken facets/subagents port to Copilot CLI with partial "
        "fidelity; see matrix.",
        "",
        "## Scope, assumptions, and evidence quality",
        "Grounded in the six captured facet/subagent roots.",
        "Evidence: " + EVIDENCE_NAME,
        "Roadmap file: " + ROADMAP_NAME,
        "Roadmap status: Landed",
        "Roadmap path: docs/implementation-plans/"
        "2026-08-20-pinned-dispatch-fallback/plan.md",
        "",
        "## Polytoken runtime/workflow model",
        "Facets compose prompts via transclude; subagents return via "
        "exit_tool.",
        "",
        "## Existing ed3d/Copilot workflow model",
        "Copilot CLI uses agents, skills, and hooks.",
        "",
        "## Capability-by-capability equivalence matrix",
        "| Capability | Polytoken mechanism | Copilot CLI equivalent | "
        "Verdict | Semantic IDs |",
        "|---|---|---|---|---|",
    ]
    for cap in parser.CAPABILITY_IDS:
        sids = ", ".join(CAP_TO_SEM[cap])
        lines.append("| %s | mechanism-%s | equivalent-%s | %s | %s |"
                     % (cap, cap, cap, VERDICTS[cap], sids))
    lines += [
        "",
        "## Quality-impact/cost ranking",
        "1. Highest impact: RESEARCH_DECOMPOSITION.",
        "",
        "## Case study: research failure and missing controls",
        "Missing evidence controls let an unresolved case study go "
        "undetected.",
    ]
    for case in evidence["case_study_citations"]:
        lines.append("- %s: %s (%s)"
                     % (case["label"], case["uri"], case["status"]))
    lines += [
        "",
        "## Recommended MVP ports, deferred work, and explicit non-goals",
        "- **RECOMMENDATION:** Port the plan facet control-plane handoff.",
        "  - benefit: restores plan-then-execute gating",
        "  - touched_files: plugins/ed3d-plan-and-execute",
        "  - mechanism: custom agent + slash command",
        "  - testability: hermetic offline test",
        "  - success_measurement: handoff passes validator",
        "- **RECOMMENDATION:** Re-express subagents as Copilot agents.",
        "  - benefit: preserves evidence contracts",
        "  - touched_files: plugins/ed3d-basic-agents",
        "  - mechanism: agent frontmatter grants",
        "  - testability: fixture-based replay",
        "  - success_measurement: replay replays cleanly",
        "",
        "## Compatibility and version risks",
        "Hook schema coupled to installed CLI version.",
        "",
        "## Source index",
    ]
    for root in roots:
        label = "root-" + root.rstrip("/").split("/")[-1].replace(".", "-")
        lines.append("- %s: %s" % (label, root))
    for record in evidence["local_citations"]:
        label = "local-" + record["path"].replace("/", "-").replace(".", "-")
        lines.append("- %s: %s" % (label, record["path"]))
    lines.append("- hooks-ref: " + URL_REF)
    return "\n".join(lines) + "\n"


def build_fixture(tmpdir, content=None, audit_mutator=None,
                  roadmap_text=None, evidence_mutator=None):
    """Write a full three-artifact fixture; return the paths + objects."""
    content = dict(DEFAULT_CONTENT) if content is None else dict(content)
    evidence = build_evidence(content)
    if evidence_mutator is not None:
        evidence_mutator(evidence)
    audit = build_audit(evidence)
    if audit_mutator is not None:
        audit = audit_mutator(audit)
    if roadmap_text is None:
        roadmap_text = VALID_ROADMAP_TEXT

    audit_path = os.path.join(tmpdir, AUDIT_NAME)
    evidence_path = os.path.join(tmpdir, EVIDENCE_NAME)
    roadmap_path = os.path.join(tmpdir, ROADMAP_NAME)
    with open(audit_path, "w", encoding="utf-8") as handle:
        handle.write(audit)
    with open(evidence_path, "w", encoding="utf-8") as handle:
        json.dump(evidence, handle, indent=2, sort_keys=True)
    with open(roadmap_path, "w", encoding="utf-8") as handle:
        handle.write(roadmap_text)

    catmap_path = os.path.join(tmpdir, "catmap.json")
    with open(catmap_path, "w", encoding="utf-8") as handle:
        json.dump({r["uri"]: r.get("content", "") for r in
                   evidence["resources"]}, handle)
    fakecat_path = os.path.join(tmpdir, "fakecat.py")
    with open(fakecat_path, "w", encoding="utf-8") as handle:
        handle.write(FAKE_CAT)
    log_path = os.path.join(tmpdir, "cat.log")
    return {
        "audit": audit_path,
        "evidence": evidence_path,
        "roadmap": roadmap_path,
        "fakecat": fakecat_path,
        "catmap": catmap_path,
        "log": log_path,
        "evidence_obj": evidence,
        "audit_text": audit,
    }


def cat_command(fixture):
    """Test-only PORTABILITY_VFS_CAT_COMMAND pointing at the fake cat."""
    return "%s %s %s %s" % (sys.executable, fixture["fakecat"],
                            fixture["catmap"], fixture["log"])


def run_validator(fixture):
    return subprocess.run(
        [sys.executable, os.path.join(HERE, "validate_portability_audit.py"),
         fixture["audit"], fixture["evidence"], fixture["roadmap"]],
        capture_output=True, text=True, check=False)


def run_replay(fixture, with_cat=True):
    env = os.environ.copy()
    if with_cat:
        env[replay.CAT_COMMAND_ENV] = cat_command(fixture)
    return subprocess.run(
        [sys.executable, os.path.join(HERE, "replay_portability_evidence.py"),
         fixture["evidence"]],
        capture_output=True, text=True, check=False, env=env)


def run_parser_scan(path):
    return subprocess.run(
        [sys.executable, os.path.join(HERE, "portability_evidence_parser.py"),
         "--scan", path],
        capture_output=True, text=True, check=False)


def write_temp(text, suffix):
    with tempfile.NamedTemporaryFile("w", suffix=suffix, delete=False) as h:
        h.write(text)
        return h.name


def assert_fails_validator(fixture, needle=None):
    result = run_validator(fixture)
    assert result.returncode != 0, \
        "validator unexpectedly passed:\n%s%s" % (result.stdout, result.stderr)
    if needle:
        assert needle in result.stdout + result.stderr, \
            "expected %r in:\n%s%s" % (needle, result.stdout, result.stderr)


def assert_fails_replay(fixture, needle=None, with_cat=True):
    result = run_replay(fixture, with_cat=with_cat)
    assert result.returncode != 0, \
        "replay unexpectedly passed:\n%s%s" % (result.stdout, result.stderr)
    if needle:
        assert needle in result.stdout + result.stderr, \
            "expected %r in:\n%s%s" % (needle, result.stdout, result.stderr)



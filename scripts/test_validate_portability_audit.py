def test_parser_transclude_single_and_double_quotes():
    text = ("transclude('polytoken://vfs/a.md')\n"
            "transclude(\"polytoken://vfs/b.md\")\n")
    scan = parser.scan_content(text)
    sources = [r["source"] for r in scan["references"]]
    assert sources == ["transclude", "transclude"]



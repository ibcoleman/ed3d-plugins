def test_parser_warning_parity_validator_vs_replay():
    # Malformed token inside a root's content: the shared parser emits the
    # same deterministic warning through both CLIs, and the malformed token
    # is a warning, not a dependency, so both pass.
    bad_content = dict(DEFAULT_CONTENT)
    bad_content["polytoken://facets/plan.md"] = (
        "{{ transclude(\"polytoken://system_prompts/facet.md\") }}\n"
        "{{ transclude(\"unterminated\n"
        "{{ transclude(\"polytoken://resources/plan_spec_default.md\") }}\n"
    )
    with tempfile.TemporaryDirectory() as tmp:
        fixture = build_fixture(tmp, content=bad_content)
        v_result = run_validator(fixture)
        r_result = run_replay(fixture)
        assert "parser warning:" in v_result.stderr
        assert v_result.stderr == r_result.stderr, (
            "validator and replay stderr differ:\nVALIDATOR=%r\nREPLAY=%r"
            % (v_result.stderr, r_result.stderr))
        assert v_result.returncode == 0, v_result.stdout
        assert r_result.returncode == 0, r_result.stdout


